def _bytes_note(indent: str) -> list[str]:
    """bytes 字段为什么用 ReadStringField：`reader.h` 里没有 ReadBytesField。

    霍承钧确认两者是同一实现（都走 ReadLengthDelimited + assign(ptr,len)），
    所以含内嵌 NUL 的二进制同样安全；这行注释是为了让读生成物的人
    不要把它当成笔误。
    """
    return [
        indent + "// bytes 用 ReadStringField 承载：reader.h 没有 ReadBytesField，",
        indent + "// 两者都是 length-delimited 拷贝（含内嵌 NUL 也安全），字节完全一致。",
    ]


def _needs_has_flag(field: ast.Field) -> bool:
    """optional 字段与 message 字段都需要 presence 标记。"""
    return field.optional or field.type_ref.is_message


def _fallback_enum_name(enum: ast.EnumDecl) -> str:
    zero = enum.zero_value_name()
    if zero is not None:
        return zero
    return enum.values[0].name if enum.values else "UNKNOWN"


def _element_zero(ref: ast.TypeRef) -> str:
    if ref.resolved_kind == ast.KIND_ENUM:
        enum = ref.resolved_node
        zero = enum.zero_value_name() if enum is not None else None
        if zero is None:
            return "static_cast<{}>(0)".format(naming.cpp_type(ref))
        return "{}::{}".format(naming.cpp_type(ref), zero)
    if ref.resolved_kind == ast.KIND_SCALAR:
        return naming.SCALAR_ZERO[ref.name]
    return "0"


def _read_field_method(ref: ast.TypeRef) -> str:
    if ref.resolved_kind == ast.KIND_ENUM:
        return "ReadInt32Field"
    return naming.SCALAR_READ_FIELD[ref.name]


def _element_read(
    ref: ast.TypeRef, member: str, reader: str, with_wire_type: bool
) -> list[str]:
    """生成"读一个元素并 push_back"的语句（不含缩进）。"""
    if ref.resolved_kind == ast.KIND_ENUM:
        enum_cpp = naming.cpp_type(ref)
        if with_wire_type:
            return [
                "std::int32_t raw_value = 0;",
                "if (!{}ReadInt32Field(wire_type, &raw_value)) return false;".format(reader),
                "{}.push_back(static_cast<{}>(raw_value));".format(member, enum_cpp),
            ]
        return [
            "std::int32_t raw_value = 0;",
            "if (!{}ReadInt32(&raw_value)) return false;".format(reader),
            "{}.push_back(static_cast<{}>(raw_value));".format(member, enum_cpp),
        ]
    scalar = ref.name
    type_name = naming.cpp_type(ref)
    if with_wire_type:
        return [
            "{} value = {};".format(type_name, _element_zero(ref)),
            "if (!{}{}(wire_type, &value)) return false;".format(reader, _read_field_method(ref)),
            "{}.push_back(value);".format(member),
        ]
    return [
        "{} value = {};".format(type_name, _element_zero(ref)),
        "if (!{}{}(&value)) return false;".format(reader, naming.SCALAR_READ_BARE[scalar]),
        "{}.push_back(value);".format(member),
    ]


def _packed_write_statement(ref: ast.TypeRef) -> str:
    if ref.resolved_kind == ast.KIND_ENUM:
        return "packed.WriteEnum(static_cast<std::int32_t>(value));"
    return "packed.{}(value);".format(naming.SCALAR_WRITE[ref.name])


def _indent(statements: list[str], indent: str) -> list[str]:
    return ["{}{}".format(indent, line) for line in statements]


def _meta_header_comment(widths: list[int]) -> str:
    names = [
        "number",
        "name",
        "type",
        "type_name",
        "repeated",
        "optional",
        "has_default",
        "default_value",
    ]
    cells = [
        name if index == len(names) - 1 else (name + ",").ljust(widths[index] + 1)
        for index, name in enumerate(names)
    ]
    return "      // " + " ".join(cells)


def generate(node: ast.FileNode, options: GenerateOptions) -> tuple[str, str]:
    """返回 (header_text, source_text)。"""
    generator = CppGenerator(node, options)
    return generator.header_text(), generator.source_text()
