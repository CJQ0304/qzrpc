    def _stub_method_impl(self, service: ast.ServiceDecl, method: ast.RpcDecl) -> list[str]:
        stub = naming.stub_class_name(service.name)
        head = "qzrpc::Status {}::{}(".format(stub, method.name)
        indent = " " * len(head)
        lines = [
            "{}const {}& request, {}* response,".format(
                head, naming.cpp_type(method.request), naming.cpp_type(method.response)
            ),
            "{}const qzrpc::rpc::CallOptions& options) {{".format(indent),
        ]
        if method.is_idempotent:
            lines += [
                "  qzrpc::rpc::CallOptions opts = options;",
                "  if (!opts.idempotent) opts.idempotent = true;  // IDL 声明了 [idempotent = true]",
            ]
            call_opts = "opts"
        else:
            lines.append("  // 非幂等方法：不擅自打开重试开关（尊重调用方在 options 里显式设置的值）")
            call_opts = "options"
        lines += [
            "  return channel_.Call({}(), request, response, {});".format(
                naming.method_id_function_name(method.name), call_opts
            ),
            "}",
        ]
        return lines

    def _base_impl(self, service: ast.ServiceDecl) -> list[str]:
        base = naming.base_class_name(service.name)
        return [
            _RULE_S,
            "// 服务端基类",
            _RULE_S,
            "{}::~{}() = default;".format(base, base),
            "",
        ]

    def _dispatcher_impl(self, service: ast.ServiceDecl) -> list[str]:
        base = naming.base_class_name(service.name)
        stub = naming.stub_class_name(service.name)
        dispatcher = naming.dispatcher_class_name(service.name)
        lines = [
            _RULE_S,
            "// 服务端分发器",
            _RULE_S,
        ] + wrap_signature(
            "{}::{}( ".format(dispatcher, dispatcher).replace("( ", "("),
            ["{}* service".format(base), "qzrpc::rpc::Dispatcher* dispatcher"],
            ")",
        ) + [
            "    : service_(service), dispatcher_(dispatcher) {",
            "  if (service_ == nullptr || dispatcher_ == nullptr) {",
            '    error_ = "{}: null service or dispatcher";'.format(dispatcher),
            "    return;",
            "  }",
            "",
            "  struct MethodDecl {",
            "    std::uint32_t method_id;",
            "    const char* full_name;",
            "    const char* method_name;",
            "    const char* request_type;",
            "    const char* response_type;",
            "    bool idempotent;",
            "    bool method_id_overridden;  // IDL 里是否写了 [method_id = 0x...]",
            "    qzrpc::rpc::MethodHandler handler;",
            "  };",
            "",
            "  const MethodDecl decls[] = {",
        ]
        for method in service.methods:
            handler = naming.handler_name(method.name, service.name, self._need_svc_prefix)
            id_expr = "{}::{}()".format(stub, naming.method_id_function_name(method.name))
            lines += [
                "      {"
                + id_expr
                + ", "
                + naming.cpp_string_literal(method.full_name)
                + ", "
                + naming.cpp_string_literal(method.name)
                + ",",
                "       {}, {}, {},".format(
                    naming.cpp_string_literal(method.request.resolved_name),
                    naming.cpp_string_literal(method.response.resolved_name),
                    "true" if method.is_idempotent else "false",
                ),
                "       {},  // method_id_overridden".format(
                    "true" if method.explicit_method_id is not None else "false"
                ),
                "       [this](const char* p, std::size_t n, std::string* o,",
                "              qzrpc::rpc::ServerContext* c) {",
                "         return {}(service_, p, n, o, c);".format(handler),
                "       }},",
            ]
        lines += [
            "  };",
            "",
            "  for (const MethodDecl& decl : decls) {",
            "    if (!dispatcher_->Register(decl.method_id, decl.full_name, decl.handler, &error_)) {",
            "      return;  // 路由表注册失败（通常是 method_id 冲突）",
            "    }",
            "    qzrpc::rpc::MethodInfo info;",
            "    info.method_id = decl.method_id;",
            "    info.full_name = decl.full_name;",
            "    info.package_name = {};".format(naming.cpp_string_literal(self.package)),
            "    info.service_name = {};".format(naming.cpp_string_literal(service.name)),
            "    info.method_name = decl.method_name;",
            "    info.request_type = decl.request_type;",
            "    info.response_type = decl.response_type;",
            "    info.idempotent = decl.idempotent;",
            "    info.method_id_overridden = decl.method_id_overridden;",
            "    if (!qzrpc::rpc::ServiceRegistry::Instance().RegisterMethod(info, &error_)) {",
            "      return;  // 元信息登记失败（通常是与已有方法 id 冲突，L2 检测）",
            "    }",
            "  }",
            "  ok_ = true;",
            "}",
            "",
            "{}::~{}() = default;".format(dispatcher, dispatcher),
            "",
        ]
        return lines

    def _factory_impl(self, service: ast.ServiceDecl) -> list[str]:
        base = naming.base_class_name(service.name)
        dispatcher = naming.dispatcher_class_name(service.name)
        function = naming.register_function_name(service.name)
        head = "std::unique_ptr<{}> {}(".format(dispatcher, function)
        return wrap_signature(
            head,
            [
                "{}* service".format(base),
                "qzrpc::rpc::Dispatcher* dispatcher",
                "std::string* error",
            ],
            ") {",
        ) + [
            "  std::unique_ptr<{}> guard(".format(dispatcher),
            "      new {}(service, dispatcher));".format(dispatcher),
            "  if (!guard->ok()) {",
            "    if (error != nullptr) *error = guard->error_message();",
            "    return nullptr;",
            "  }",
            "  return guard;",
            "}",
            "",
        ]


