    def _source_handlers(self) -> list[str]:
        if not self.node.services:
            return []
        lines = [
            _RULE_S,
            "// 方法处理器（匿名 namespace：不被外部链接看到，永不与其他翻译单元冲突）",
            _RULE_S,
            "namespace {",
            "",
        ]
        for service in self.node.services:
            for method in service.methods:
                lines += self._handler_impl(service, method)
        lines += ["}  // namespace", ""]
        return lines

    def _qualified(self, name: str) -> str:
        """加包前缀的限定名。包名里的 '.' 必须换成 C++ 的 '::'。"""
        if not self.package:
            return name
        return "{}::{}".format(self.package.replace(".", "::"), name)

    def _handler_impl(self, service: ast.ServiceDecl, method: ast.RpcDecl) -> list[str]:
        handler = naming.handler_name(method.name, service.name, self._need_svc_prefix)
        base = self._qualified(naming.base_class_name(service.name))
        request_type = self._qualified(naming.cpp_type(method.request))
        response_type = self._qualified(naming.cpp_type(method.response))
        head = "qzrpc::Status {}(".format(handler)
        indent = " " * len(head)
        return [
            "{}{}* service, const char* payload,".format(head, base),
            "{}std::size_t payload_len, std::string* out,".format(indent),
            "{}qzrpc::rpc::ServerContext* ctx) {{".format(indent),
            "  (void)ctx;",
            "  {} request;".format(request_type),
            "  if (!qzrpc::serde::Serializer::ParseFromArray(payload, payload_len, &request)) {",
            '    return qzrpc::Status::SerializeError("{}: decode request failed");'.format(
                method.full_name
            ),
            "  }",
            "  {} response;".format(response_type),
            "  qzrpc::Status status = service->{}(request, &response);".format(method.name),
            "  if (!status.ok()) return status;",
            "  if (!qzrpc::serde::Serializer::SerializeToString(response, out)) {",
            '    return qzrpc::Status::SerializeError("{}: encode response failed");'.format(
                method.full_name
            ),
            "  }",
            "  return qzrpc::Status::Ok();",
            "}",
            "",
        ]

