"""C++ 生成器（G-08）：把 AST 变成 `generated/<base>.qz.h` 与 `.qz.cpp`。

输出契约见 doc 04 §6.3 / §6.4。三条不可退让的原则：

1. **只调用 src/ 公共头里确实存在的符号**。生成器里每出现一个运行时 API，
   都必须能在 `src/**/*.h` 里找到声明（对照 doc 04 §6.6 的自检表）。
2. **同一输入必须逐字节幂等**：不含时间戳（除非显式传入）、不含绝对路径、
   不依赖任何遍历顺序不确定的容器。
3. **同一规则只写一处**：访问器名/成员名/has flag 名/类型映射全部来自
   naming.py，生成器自己不拼第二套。

代码是"拼字符串"而不是模板引擎：模板引擎会把"改一行生成物"变成"先读一遍
模板语言"，而这个生成器本身就是要被人读、被人改的。
"""

from __future__ import annotations

from dataclasses import dataclass

from . import ast_nodes as ast
from . import methodid
from . import naming

GENERATOR_VERSION = "1.0.0"
PROTOCOL_VERSION = 1
RUNTIME_REQUIREMENT = "qzrpc >= 0.1.0（见 docs/03-wire-protocol.md）"

# 生成时间默认不写：doc 04 §6.1 希望它存在，但"幂等"是更硬的要求
# （同一输入两次生成的产物必须逐字节相同，否则 git diff 永远在抖）。
# 需要写时间时显式给 --timestamp 或环境变量 SOURCE_DATE_EPOCH。
_REPRODUCIBLE_NOTE = "<reproducible>（默认不写时间；可用 --timestamp 或 SOURCE_DATE_EPOCH）"

_RULE_H = "// " + "-" * 75
_RULE_S = "// " + "=" * 75


MAX_LINE_WIDTH = 100


def wrap_signature(prefix: str, params: list[str], suffix: str = "") -> list[str]:
    """渲染 `prefix(a, b, c)suffix`，超过 100 列就断行并把续行对齐到左括号后。

    只做一件事，但所有函数声明/定义都用它 —— 生成物里"有的地方折行、有的
    地方不折"会让人怀疑是不是手改过。
    """
    one_line = "{}{}{}".format(prefix, ", ".join(params), suffix)
    if len(one_line) <= MAX_LINE_WIDTH or not params:
        return [one_line]
    indent = " " * len(prefix)
    lines: list[str] = []
    current = prefix
    for index, param in enumerate(params):
        tail = suffix if index == len(params) - 1 else ","
        piece = param + tail
        separator = "" if current.endswith("(") else " "
        if len(current) + len(separator) + len(piece) <= MAX_LINE_WIDTH:
            current += separator + piece
        else:
            lines.append(current)
            current = indent + piece
    lines.append(current)
    return lines


@dataclass
class GenerateOptions:
    source_rel_path: str
    file_stem: str
    timestamp: str = ""
    version: str = GENERATOR_VERSION


class CppGenerator:
    def __init__(self, node: ast.FileNode, options: GenerateOptions) -> None:
        self.node = node
        self.opt = options
        self.package = node.package
        self.guard = naming.header_guard(self.package, "{}.qz".format(options.file_stem))
        self._need_svc_prefix = naming.needs_service_prefix(node.services)

    # ==================================================================
    # 公共入口
    # ==================================================================

    def header_text(self) -> str:
        lines: list[str] = []
        lines += self._file_banner()
        lines += [
            "",
            "#pragma once",
            "#ifndef {}".format(self.guard),
            "#define {}".format(self.guard),
            "",
        ]
        lines += self._header_includes()
        lines.append("")
        lines += naming.namespace_open(self.package)
        if self.package:
            lines.append("")
        lines += self._header_enums()
        lines += self._header_messages()
        lines += self._header_services()
        lines += naming.namespace_close(self.package)
        lines += ["", "#endif  // {}".format(self.guard)]
        return "\n".join(lines) + "\n"

    def source_text(self) -> str:
        lines: list[str] = []
        lines += self._file_banner()
        lines += [
            "",
            '#include "{}"  // 由构建系统保证 generated/ 在 include 路径中'.format(
                naming.generated_header_name(self.opt.file_stem)
            ),
            "",
            "#include <utility>",
            "",
            '#include "serialize/reader.h"      // qzrpc::serde::Reader（Decode 需要完整类型）',
            '#include "serialize/serializer.h"  // qzrpc::serde::Serializer（处理器使用）',
            '#include "serialize/writer.h"      // qzrpc::serde::Writer（Encode 需要完整类型）',
            "",
        ]
        lines += naming.namespace_open(self.package)
        if self.package:
            lines.append("")
        lines += self._source_enums()
        lines += self._source_messages()
        lines += self._source_handlers()
        lines += self._source_services()
        lines += naming.namespace_close(self.package)
        return "\n".join(lines) + "\n"

    # ==================================================================
    # 文件头 / include
    # ==================================================================

    def _file_banner(self) -> list[str]:
        stamp = self.opt.timestamp or _REPRODUCIBLE_NOTE
        rule = "// " + "=" * 77
        return [
            rule,
            "// Generated by qzcodegen. DO NOT EDIT.",
            "// 由 qzcodegen {} 生成，请勿手工修改。".format(self.opt.version),
            "// 源文件   : {}".format(self.opt.source_rel_path),
            "// 生成时间 : {}".format(stamp),
            "// 协议版本 : {}".format(PROTOCOL_VERSION),
            "// 运行时   : {}".format(RUNTIME_REQUIREMENT),
            rule,
        ]

    def _header_includes(self) -> list[str]:
        return [
            "#include <cstddef>",
            "#include <cstdint>",
            "#include <memory>",
            "#include <string>",
            "#include <utility>   // std::move（内联 setter 使用）",
            "#include <vector>",
            "",
            '#include "client/channel.h"          // qzrpc::rpc::Channel / CallOptions',
            '#include "common/status.h"           // qzrpc::Status',
            '#include "serialize/message.h"       // qzrpc::serde::Message / FieldMeta',
            '#include "server/dispatcher.h"       // qzrpc::rpc::Dispatcher / ServerContext',
            '#include "server/service_registry.h" // qzrpc::rpc::ServiceRegistry / MethodInfo',
        ]

    # ==================================================================
    # 枚举
    # ==================================================================

    def _header_enums(self) -> list[str]:
        enums = self.node.iter_enums()
        if not enums:
            return []
        lines = [_RULE_H, "// 枚举", _RULE_H]
        for enum in enums:
            lines += self._enum_decl(enum)
        return lines

    def _enum_decl(self, enum: ast.EnumDecl) -> list[str]:
        width = max((len(v.name) for v in enum.values), default=0)
        lines = ["enum class {} : std::int32_t {{".format(enum.cpp_name)]
        for value in enum.values:
            lines.append("  {}{} = {},".format(
                value.name, " " * (width - len(value.name)), value.number
            ))
        lines += [
            "};",
            "",
            '// 枚举值名；未知值返回 "{}"。'.format(_fallback_enum_name(enum)),
            "const char* {}({} value);".format(
                naming.enum_name_function(enum.cpp_name), enum.cpp_name
            ),
            "",
            "// 按名解析；失败返回 false 且不修改 *out。",
            "bool {}(const std::string& name, {}* out);".format(
                naming.enum_parse_function(enum.cpp_name), enum.cpp_name
            ),
            "",
        ]
        return lines

    def _source_enums(self) -> list[str]:
        lines: list[str] = []
        for enum in self.node.iter_enums():
            lines += [_RULE_S, "// 枚举 {}".format(enum.cpp_name), _RULE_S]
            name_width = max((len(v.name) for v in enum.values), default=0)
            lines.append("const char* {}({} value) {{".format(
                naming.enum_name_function(enum.cpp_name), enum.cpp_name
            ))
            lines.append("  switch (value) {")
            for value in enum.values:
                lines.append('    case {}::{}:{} return "{}";'.format(
                    enum.cpp_name,
                    value.name,
                    " " * (name_width - len(value.name)),
                    value.name,
                ))
            lines += ["  }", '  return "{}";'.format(_fallback_enum_name(enum)), "}", ""]

            conditions = ['name == "{}"'.format(v.name) for v in enum.values]
            cond_width = max((len(c) for c in conditions), default=0)
            lines.append("bool {}(const std::string& name, {}* out) {{".format(
                naming.enum_parse_function(enum.cpp_name), enum.cpp_name
            ))
            lines.append("  if (out == nullptr) return false;")
            for value, condition in zip(enum.values, conditions):
                lines.append("  if ({}){} {{ *out = {}::{}; return true; }}".format(
                    condition,
                    " " * (cond_width - len(condition)),
                    enum.cpp_name,
                    value.name,
                ))
            lines += ["  return false;", "}", ""]
        return lines

    # ==================================================================
    # 消息类声明
    # ==================================================================

    def _header_messages(self) -> list[str]:
        lines: list[str] = []
        for message in self.node.iter_messages():
            lines += self._message_decl(message)
        return lines

    def _message_decl(self, message: ast.MessageDecl) -> list[str]:
        name = message.cpp_name
        fields = message.sorted_fields()
        lines = [
            _RULE_H,
            "// 消息 {}".format(message.full_name(self.package)),
            _RULE_H,
            "class {} final : public qzrpc::serde::Message {{".format(name),
            " public:",
            "  {}();".format(name),
            "  ~{}() override;".format(name),
            "",
            "  {}(const {}&) = default;".format(name, name),
            "  {}& operator=(const {}&) = default;".format(name, name),
            "  {}({}&&) = default;".format(name, name),
            "  {}& operator=({}&&) = default;".format(name, name),
            "",
            '  // 返回 "{}"。'.format(message.full_name(self.package)),
            "  const char* TypeName() const override;",
            "  // 全部字段恢复默认值，并清空 unknown fields。",
            "  void Clear() override;",
            "  // 按字段号升序编码；返回 false 表示编码失败。",
            "  bool Encode(qzrpc::serde::Writer* writer) const override;",
            "  // 从 reader 解析（范围恰好是消息体）；未知字段保留到 unknown_fields()。",
            "  bool Decode(qzrpc::serde::Reader* reader) override;",
            "  // 字段元数据表；*count 写入元素个数。",
            "  const qzrpc::serde::FieldMeta* Fields(std::size_t* count) const override;",
        ]
        for field in fields:
            lines.append("")
            lines += self._field_accessors(field)
        lines += ["", " private:"]
        if not fields:
            lines.append("  // 该消息没有声明任何字段。")
        for field in fields:
            lines.append("  {}".format(self._member_decl(field)))
            if _needs_has_flag(field):
                lines.append("  {}".format(self._has_flag_decl(field)))
        lines += ["};", ""]
        return lines

    def _member_decl(self, field: ast.Field) -> str:
        member = naming.member_name(field.name)
        ref = field.type_ref
        if field.repeated:
            return "{} {};".format(naming.cpp_container_type(ref), member)
        if ref.is_scalar and ref.name in ("string", "bytes"):
            return "std::string {};".format(member)
        if ref.is_message:
            return "{} {};".format(naming.cpp_type(ref), member)
        return "{} {}{{{}}};".format(naming.cpp_type(ref), member, naming.zero_expr(field))

    def _has_flag_decl(self, field: ast.Field) -> str:
        return "bool {}{{false}};".format(naming.has_flag_name(field.name))

    def _field_comment(self, field: ast.Field) -> str:
        label = "{} ".format(field.label) if field.label else ""
        text = "// field {}: {}{} {}".format(
            field.tag, label, naming.idl_type_name(field.type_ref), field.name
        )
        notes: list[str] = []
        if field.default is not None:
            notes.append("默认值 {}，等于默认值时不编码".format(field.default.text))
        if field.repeated:
            notes.append("packed 编码" if field.packed_effective else "逐元素带 tag，不 packed")
        if field.optional:
            notes.append("有 presence 语义")
        if field.type_ref.is_message:
            notes.append("message 字段永远有 presence")
        if field.deprecated:
            notes.append("已废弃")
        if notes:
            text += " （{}）".format("；".join(notes))
        return text

    # ---------------- 访问器 ----------------

    def _field_accessors(self, field: ast.Field) -> list[str]:
        ref = field.type_ref
        names = naming.accessor_names(field.name)
        member = naming.member_name(field.name)
        has_flag = naming.has_flag_name(field.name)
        cpp = naming.cpp_type(ref)
        lines = ["  " + self._field_comment(field)]

        if field.repeated:
            lines.append("  std::size_t {}() const noexcept {{ return {}.size(); }}".format(
                names["size"], member
            ))
            if ref.is_scalar and ref.name in ("string", "bytes"):
                lines += [
                    "  const std::string& {}(std::size_t index) const {{ return {}[index]; }}".format(
                        names["get"], member
                    ),
                    "  void {}(std::size_t index, std::string value) {{ {}[index] = std::move(value); }}".format(
                        names["set"], member
                    ),
                    "  void {}(std::string value) {{ {}.push_back(std::move(value)); }}".format(
                        names["add"], member
                    ),
                ]
            elif ref.is_message:
                lines += [
                    "  const {}& {}(std::size_t index) const {{ return {}[index]; }}".format(
                        cpp, names["get"], member
                    ),
                    "  {}* {}(std::size_t index) {{ return &{}[index]; }}".format(
                        cpp, names["mutable"], member
                    ),
                    "  void {}(std::size_t index, const {}& value) {{ {}[index] = value; }}".format(
                        names["set"], cpp, member
                    ),
                    "  {}* {}() {{ {}.emplace_back(); return &{}.back(); }}".format(
                        cpp, names["add"], member, member
                    ),
                    "  void {}(const {}& value) {{ {}.push_back(value); }}".format(
                        names["add"], cpp, member
                    ),
                ]
            else:
                lines += [
                    "  {} {}(std::size_t index) const {{ return {}[index]; }}".format(
                        cpp, names["get"], member
                    ),
                    "  void {}(std::size_t index, {} value) {{ {}[index] = value; }}".format(
                        names["set"], cpp, member
                    ),
                    "  void {}({} value) {{ {}.push_back(value); }}".format(
                        names["add"], cpp, member
                    ),
                ]
            lines += [
                "  const std::vector<{}>& {}() const noexcept {{ return {}; }}".format(
                    cpp, names["get"], member
                ),
                "  std::vector<{}>* {}() noexcept {{ return &{}; }}".format(
                    cpp, names["mutable"], member
                ),
                "  void {}() noexcept {{ {}.clear(); }}".format(names["clear"], member),
            ]
            return lines

        if ref.is_message:
            return lines + [
                "  const {}& {}() const noexcept {{ return {}; }}".format(cpp, names["get"], member),
                "  {}* {}() noexcept {{ {} = true; return &{}; }}".format(
                    cpp, names["mutable"], has_flag, member
                ),
                "  void {}(const {}& value) {{ {} = value; {} = true; }}".format(
                    names["set"], cpp, member, has_flag
                ),
                "  bool {}() const noexcept {{ return {}; }}".format(names["has"], has_flag),
                "  void {}() noexcept {{ {}.Clear(); {} = false; }}".format(
                    names["clear"], member, has_flag
                ),
            ]

        if ref.is_scalar and ref.name in ("string", "bytes"):
            lines.append(
                "  const std::string& {}() const noexcept {{ return {}; }}".format(
                    names["get"], member
                )
            )
            if field.optional:
                lines += [
                    "  void {}(std::string value) {{ {} = std::move(value); {} = true; }}".format(
                        names["set"], member, has_flag
                    ),
                    "  std::string* {}() noexcept {{ {} = true; return &{}; }}".format(
                        names["mutable"], has_flag, member
                    ),
                    "  bool {}() const noexcept {{ return {}; }}".format(names["has"], has_flag),
                    "  void {}() noexcept {{ {}.clear(); {} = false; }}".format(
                        names["clear"], member, has_flag
                    ),
                ]
            else:
                lines += [
                    "  void {}(std::string value) {{ {} = std::move(value); }}".format(
                        names["set"], member
                    ),
                    "  std::string* {}() noexcept {{ return &{}; }}".format(names["mutable"], member),
                ]
            return lines

        lines.append("  {} {}() const noexcept {{ return {}; }}".format(cpp, names["get"], member))
        if field.optional:
            lines += [
                "  void {}({} value) noexcept {{ {} = value; {} = true; }}".format(
                    names["set"], cpp, member, has_flag
                ),
                "  bool {}() const noexcept {{ return {}; }}".format(names["has"], has_flag),
                "  void {}() noexcept {{ {} = {}; {} = false; }}".format(
                    names["clear"], member, naming.zero_expr(field), has_flag
                ),
            ]
        else:
            lines.append("  void {}({} value) noexcept {{ {} = value; }}".format(
                names["set"], cpp, member
            ))
        return lines

    # ==================================================================
    # 消息类实现
    # ==================================================================

    def _source_messages(self) -> list[str]:
        lines: list[str] = []
        for message in self.node.iter_messages():
            lines += self._message_impl(message)
        return lines

    def _message_impl(self, message: ast.MessageDecl) -> list[str]:
        name = message.cpp_name
        fields = message.sorted_fields()
        lines = [
            _RULE_S,
            "// 消息 {}".format(name),
            _RULE_S,
            "{}::{}() = default;".format(name, name),
            "{}::~{}() = default;".format(name, name),
            "",
            'const char* {}::TypeName() const {{ return "{}"; }}'.format(
                name, message.full_name(self.package)
            ),
            "",
            "void {}::Clear() {{".format(name),
        ]
        for field in fields:
            lines += self._clear_statement(field)
        lines += ["  ClearUnknownFields();", "}", ""]
        lines += self._encode_impl(name, fields)
        lines.append("")
        lines += self._decode_impl(name, fields)
        lines.append("")
        lines += self._fields_impl(name, fields)
        lines.append("")
        return lines

    def _clear_statement(self, field: ast.Field) -> list[str]:
        member = naming.member_name(field.name)
        has_flag = naming.has_flag_name(field.name)
        ref = field.type_ref
        if field.repeated:
            return ["  {}.clear();".format(member)]
        if ref.is_message:
            return ["  {}.Clear();".format(member), "  {} = false;".format(has_flag)]
        out: list[str] = []
        if ref.is_scalar and ref.name in ("string", "bytes"):
            out.append("  {}.clear();".format(member))
        else:
            out.append("  {} = {};".format(member, naming.zero_expr(field)))
        if field.optional:
            out.append("  {} = false;".format(has_flag))
        return out

    # ---------------- Encode ----------------

    def _encode_impl(self, name: str, fields: list[ast.Field]) -> list[str]:
        lines = [
            "bool {}::Encode(qzrpc::serde::Writer* writer) const {{".format(name),
            "  if (writer == nullptr) return false;",
        ]
        if fields:
            lines.append("  namespace wt = qzrpc::serde;  // 仅为可读性")
        for field in fields:
            lines.append("")
            lines.append("  " + self._field_comment(field))
            lines += self._encode_field(field)
        lines.append("")
        # message.h 承诺"读改写不丢字段"，这句话必须由 Encode 兑现：
        # Decode 把未知字段原样存进 unknown_fields()，Encode 就得把它们写回去，
        # 否则网关/代理这类"收下来再转发"的场景会静默丢字段。
        # UnknownField::raw 不含 tag（见 message.h），所以 tag 要重建。
        lines += [
            "  // 未知字段原样追加（proto3 语义：读进来再写出去不丢字段）。",
            "  // raw 不含 tag，所以 tag 由 number + wire_type 重建；",
            "  // 但 raw **包含** wire_type=2 的长度前缀，因此这里只 WriteRaw，" ,
            "  // 绝不能再补一个长度前缀（补了就会让对端把负载首字节读成长度）。",
            "  for (const qzrpc::serde::UnknownField& unknown : unknown_fields()) {",
            "    writer->WriteTag(unknown.number, unknown.wire_type);",
            "    writer->WriteRaw(unknown.raw.data(), unknown.raw.size());",
            "  }",
        ]
        lines += ["  return true;", "}"]
        return lines

    def _tag_line(self, field: ast.Field, indent: str, wire_type: str = "") -> str:
        """写 tag 的那一行。

        `wire_type` 必须能显式覆盖：packed 字段的 tag 永远是 kLengthDelimited，
        即使元素类型本身是 varint/fixed（这是 protobuf packed 的定义）。
        """
        kind = wire_type or naming.wire_type_enum(field.type_ref)
        return "{}writer->WriteTag({}, static_cast<std::uint8_t>(wt::WireType::{}));".format(
            indent, field.tag, kind
        )

    def _write_single(self, ref: ast.TypeRef, value: str, indent: str) -> str:
        if ref.is_scalar:
            if ref.name == "string":
                return "{}writer->WriteString({});".format(indent, value)
            if ref.name == "bytes":
                return "{}writer->WriteBytes({}.data(), {}.size());".format(indent, value, value)
            return "{}writer->{}({});".format(indent, naming.SCALAR_WRITE[ref.name], value)
        if ref.is_enum:
            return "{}writer->WriteEnum(static_cast<std::int32_t>({}));".format(indent, value)
        raise AssertionError("message 字段没有单值写出路径")

    def _encode_field(self, field: ast.Field) -> list[str]:
        member = naming.member_name(field.name)
        ref = field.type_ref
        out: list[str] = []

        if field.repeated:
            if field.packed_effective:
                out.append("  if (!{}.empty()) {{".format(member))
                out.append("    qzrpc::serde::Writer packed;")
                out.append("    for ({} value : {}) {}".format(
                    naming.cpp_type(ref), member, _packed_write_statement(ref)
                ))
                out.append(self._tag_line(field, "    ", "kLengthDelimited"))
                out.append("    writer->WriteLengthDelimited(packed.data().data(), packed.size());")
                out += ["  }"]
                return out

            if ref.is_message or (ref.is_scalar and ref.name in ("string", "bytes")):
                out.append("  for (const {}& value : {}) {{".format(naming.cpp_type(ref), member))
            else:
                out.append("  for ({} value : {}) {{".format(naming.cpp_type(ref), member))
            out.append(self._tag_line(field, "    "))
            if ref.is_message:
                out += [
                    "    qzrpc::serde::Writer nested;",
                    "    if (!value.Encode(&nested)) return false;",
                    "    writer->WriteLengthDelimited(nested.data().data(), nested.size());",
                ]
            else:
                out.append(self._write_single(ref, "value", "    "))
            out.append("  }")
            return out

        if ref.is_message:
            out.append("  if ({}) {{".format(naming.has_flag_name(field.name)))
            out += [
                "    qzrpc::serde::Writer nested;",
                "    if (!{}.Encode(&nested)) return false;".format(member),
                self._tag_line(field, "    "),
                "    writer->WriteLengthDelimited(nested.data().data(), nested.size());",
                "  }",
            ]
            return out

        out.append("  if ({}) {{".format(self._encode_condition(field)))
        out += [
            self._tag_line(field, "    "),
            self._write_single(ref, member, "    "),
            "  }",
        ]
        return out

    def _encode_condition(self, field: ast.Field) -> str:
        member = naming.member_name(field.name)
        ref = field.type_ref
        if field.optional:
            return naming.has_flag_name(field.name)
        if field.default is not None:
            return "{} != {}".format(member, naming.zero_expr(field))
        if ref.is_scalar:
            if ref.name in ("string", "bytes"):
                return "!{}.empty()".format(member)
            if ref.name == "bool":
                return member
            return "{} != {}".format(member, naming.zero_expr(field))
        if ref.is_enum:
            return "{} != {}".format(member, naming.zero_expr(field))
        raise AssertionError("message 字段走 has_ 分支")

    # ---------------- Decode ----------------

    def _decode_impl(self, name: str, fields: list[ast.Field]) -> list[str]:
        if not fields:
            # 没有字段就没有 case，写成 switch 会得到 C4065；直接全当未知字段跳过。
            return [
                "bool {}::Decode(qzrpc::serde::Reader* reader) {{".format(name),
                "  if (reader == nullptr) return false;",
                "  Clear();",
                "  while (!reader->AtEnd()) {",
                "    std::uint32_t field = 0;",
                "    std::uint8_t wire_type = 0;",
                "    if (!reader->ReadTag(&field, &wire_type)) break;",
                "    std::string raw;",
                "    if (!reader->SkipFieldCapture(wire_type, &raw)) return false;",
                "    qzrpc::serde::UnknownField unknown;",
                "    unknown.number = field;",
                "    unknown.wire_type = wire_type;",
                "    unknown.raw = std::move(raw);",
                "    AddUnknownField(std::move(unknown));",
                "  }",
                "  return !reader->failed();",
                "}",
            ]
        lines = [
            "bool {}::Decode(qzrpc::serde::Reader* reader) {{".format(name),
            "  if (reader == nullptr) return false;",
            "  Clear();",
            "  while (!reader->AtEnd()) {",
            "    std::uint32_t field = 0;",
            "    std::uint8_t wire_type = 0;",
            "    if (!reader->ReadTag(&field, &wire_type)) break;",
            "",
            "    switch (field) {",
        ]
        for field in fields:
            lines += self._decode_field(field)
        lines += [
            "      default: {",
            "        std::string raw;",
            "        if (!reader->SkipFieldCapture(wire_type, &raw)) return false;",
            "        qzrpc::serde::UnknownField unknown;",
            "        unknown.number = field;",
            "        unknown.wire_type = wire_type;",
            "        unknown.raw = std::move(raw);",
            "        AddUnknownField(std::move(unknown));",
            "        break;",
            "      }",
            "    }",
            "  }",
            "  return !reader->failed();",
            "}",
        ]
        return lines

    def _decode_field(self, field: ast.Field) -> list[str]:
        member = naming.member_name(field.name)
        ref = field.type_ref
        # 需要一块作用域（局部变量/循环）的分支写成 `case N: {`；单语句分支不加大括号。
        block = field.repeated or ref.is_message or ref.is_enum
        out = ["      case {}: {{".format(field.tag)] if block else ["      case {}:".format(field.tag)]

        if field.repeated:
            if field.packed_effective:
                out += [
                    "        // packed（wire_type==2 的块）与 unpacked（逐元素）都接受",
                    "        if (wire_type ==",
                    "            static_cast<std::uint8_t>(qzrpc::serde::WireType::kLengthDelimited)) {",
                    "          const char* data = nullptr;",
                    "          std::size_t len = 0;",
                    "          if (!reader->ReadLengthDelimited(&data, &len)) return false;",
                    "          qzrpc::serde::Reader packed(data, len);",
                    "          while (!packed.AtEnd()) {",
                ]
                out += _indent(
                    _element_read(ref, member, "packed.", with_wire_type=False), "            "
                )
                out += [
                    "          }",
                    "        } else {",
                ]
                out += _indent(
                    _element_read(ref, member, "reader->", with_wire_type=True), "          "
                )
                out += ["        }", "        break;", "      }"]
                return out

            if ref.is_message:
                out += [
                    "        const char* data = nullptr;",
                    "        std::size_t len = 0;",
                    "        if (!reader->ReadLengthDelimitedField(wire_type, &data, &len)) return false;",
                    "        qzrpc::serde::Reader nested(data, len);",
                    "        {}.emplace_back();".format(member),
                    "        if (!{}.back().Decode(&nested)) return false;".format(member),
                ]
            elif ref.is_scalar and ref.name in ("string", "bytes"):
                out += [
                    "        std::string value;",
                    "        if (!reader->ReadStringField(wire_type, &value)) return false;",
                    "        {}.push_back(std::move(value));".format(member),
                ]
            else:
                out += _element_read(ref, member, "reader->", with_wire_type=True)
            out += ["        break;", "      }"]
            return out

        if ref.is_message:
            out += [
                "        const char* data = nullptr;",
                "        std::size_t len = 0;",
                "        if (!reader->ReadLengthDelimitedField(wire_type, &data, &len)) return false;",
                "        qzrpc::serde::Reader nested(data, len);",
                "        if (!{}.Decode(&nested)) return false;".format(member),
                "        {} = true;".format(naming.has_flag_name(field.name)),
                "        break;",
                "      }",
            ]
            return out

        if ref.is_enum:
            out += [
                "        std::int32_t raw_value = 0;",
                "        if (!reader->ReadInt32Field(wire_type, &raw_value)) return false;",
                "        {} = static_cast<{}>(raw_value);".format(member, naming.cpp_type(ref)),
            ]
        else:
            if ref.is_scalar and ref.name == "bytes":
                out += _bytes_note("        ")
            out.append("        if (!reader->{}(wire_type, &{})) return false;".format(
                _read_field_method(ref), member
            ))
        if field.optional:
            out.append("        {} = true;".format(naming.has_flag_name(field.name)))
        out.append("        break;")
        if block:
            out.append("      }")
        return out

    # ---------------- Fields ----------------

    def _fields_impl(self, name: str, fields: list[ast.Field]) -> list[str]:
        lines = ["const qzrpc::serde::FieldMeta* {}::Fields(std::size_t* count) const {{".format(name)]
        if not fields:
            lines += ["  if (count != nullptr) *count = 0;", "  return nullptr;", "}"]
            return lines

        rows: list[list[str]] = []
        for field in fields:
            ref = field.type_ref
            type_name = "nullptr"
            if ref.resolved_kind in (ast.KIND_MESSAGE, ast.KIND_ENUM):
                type_name = naming.cpp_string_literal(ref.resolved_name)
            default_value = "nullptr"
            if field.default is not None:
                default_value = naming.cpp_string_literal(field.default.text)
            rows.append(
                [
                    str(field.tag),
                    naming.cpp_string_literal(field.name),
                    "qzrpc::serde::FieldType::{}".format(naming.field_type_enum(ref)),
                    type_name,
                    "true" if field.repeated else "false",
                    "true" if field.optional else "false",
                    "true" if field.default is not None else "false",
                    default_value,
                ]
            )
        widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]))]

        lines.append("  static const qzrpc::serde::FieldMeta kFields[] = {")
        lines.append(_meta_header_comment(widths))
        for row in rows:
            cells = [
                cell if index == len(row) - 1 else (cell + ",").ljust(widths[index] + 1)
                for index, cell in enumerate(row)
            ]
            lines.append("      {{{}}},".format(" ".join(cells)))
        lines += [
            "  };",
            "  if (count != nullptr) *count = sizeof(kFields) / sizeof(kFields[0]);",
            "  return kFields;",
            "}",
        ]
        return lines

